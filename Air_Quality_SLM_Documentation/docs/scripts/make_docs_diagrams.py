"""
make_docs_diagrams.py - the three diagrams the documentation package needs that the
research package does not already contain.

    02_development_workflow   overall development workflow, Day 0 -> v3
    04_training_workflow      the two training runs and what was measured at each stage
    08_user_interaction       one user turn, from keystroke to answer

The other six diagrams are copied from the research package, where they are generated by
research_package/Air_Quality_SLM_Research_Package/figures/scripts/make_diagrams.py.

Every box corresponds to a file or a recorded run in the project. Nothing here is a
measurement; these are schematics.

Usage:
    ./venv/Scripts/python.exe docs/scripts/make_docs_diagrams.py
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch

DPI = 300
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8.5})

OUT = Path(__file__).resolve().parents[1] / "assets" / "diagrams"

FILL = "#eaf2fb"
EDGE = "#1f6feb"
FILL_ALT = "#eef7f2"
EDGE_ALT = "#2a9d8f"
FILL_WARN = "#fdf1e7"
EDGE_WARN = "#e76f51"
INK = "#2d3748"


def save(fig, name):
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{name}.png", dpi=DPI)
    fig.savefig(OUT / f"{name}.pdf")
    plt.close(fig)
    print(f"  wrote {name}.png / .pdf")


def box(ax, x, y, w, h, text, fill=FILL, edge=EDGE, fontsize=8, bold=False):
    ax.add_patch(
        FancyBboxPatch(
            (x, y), w, h,
            boxstyle="round,pad=0.010,rounding_size=0.018",
            linewidth=1.2, facecolor=fill, edgecolor=edge,
        )
    )
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center",
            fontsize=fontsize, color=INK, linespacing=1.35,
            fontweight="bold" if bold else "normal")


def arrow(ax, p1, p2, color="#4a5568", lw=1.2, rad=0.0, text=None, fontsize=6.5):
    ax.add_patch(
        FancyArrowPatch(p1, p2, arrowstyle="-|>", mutation_scale=11,
                        linewidth=lw, color=color,
                        connectionstyle=f"arc3,rad={rad}", shrinkA=2, shrinkB=2)
    )
    if text:
        ax.text((p1[0] + p2[0]) / 2, (p1[1] + p2[1]) / 2 + 0.014, text,
                ha="center", va="center", fontsize=fontsize, color=INK)


def canvas(w=11, h=5.6):
    fig, ax = plt.subplots(figsize=(w, h))
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")
    return fig, ax


def title(ax, text):
    ax.text(0.5, 0.965, text, ha="center", va="top", fontsize=10.5,
            fontweight="bold", color="#1a202c")


def note(ax, text):
    ax.text(0.5, 0.028, text, ha="center", va="bottom", fontsize=6.8,
            color="#718096", style="italic")


# --------------------------------------------------------------- development ---

def fig_dev_workflow():
    fig, ax = canvas(12.4, 5.9)
    title(ax, "Development workflow — Day 0 to v3 deployment")

    stages = [
        ("1. Dataset\nacquisition", "AirQualityUCI.csv\n9,357 rows x 15 cols\nMar 2004 - Apr 2005", FILL, EDGE),
        ("2. Exploration\n& validation", "Data-Convertion.ipynb\nvalidate_dataset.py\n-200 sentinel found", FILL, EDGE),
        ("3. Preprocessing\n+ split", "preprocess_air_quality.py\n70/10/20 chronological\n6,549 / 936 / 1,872", FILL, EDGE),
        ("4. Instruction\ndata", "prepare_training_data.py\n4 templates per row\n3.04M train tokens", FILL, EDGE),
        ("5. Tokenisation", "Qwen2.5-0.5B BPE\nvocab 151,665\nuint32 .bin streams", FILL, EDGE),
        ("6. v1 training", "train_slm.py\n150 steps, block 64\n279 s on CPU", FILL, EDGE),
    ]
    w, h, gap = 0.138, 0.245, 0.0265
    y = 0.60
    for i, (t, d, f, e) in enumerate(stages):
        x = 0.028 + i * (w + gap)
        box(ax, x, y, w, h, f"{t}\n\n{d}", fill=f, edge=e, fontsize=7.2)
        if i < len(stages) - 1:
            arrow(ax, (x + w + 0.004, y + h / 2), (x + w + gap - 0.004, y + h / 2))

    stages2 = [
        ("7. Evaluation\n+ diagnosis", "evaluate_v2_full.py\ngarbled output found\nflat distribution", FILL_WARN, EDGE_WARN),
        ("8. v2 continued\ntraining", "continue_training.py\n1,200 steps, block 128\ntest loss 1.4474 -> 0.5555", FILL_WARN, EDGE_WARN),
        ("9. Conversion", "export_gguf_from_\ncheckpoint.py\nF32 GGUF, qwen3, ctx 128", FILL_ALT, EDGE_ALT),
        ("10. Ollama\nregistration", "Modelfile / .improved / .v3\nnum_ctx 128\nnum_predict 48", FILL_ALT, EDGE_ALT),
        ("11. Application\nlayer", "app.py + domain_guard\n+ data_retrieval\n+ humidity_calculator", FILL_ALT, EDGE_ALT),
        ("12. v3 tag\n(deployed)", "air-quality-slm-v3:latest\nsame GGUF as v2\nsystem-prompt template", FILL_ALT, EDGE_ALT),
    ]
    y2 = 0.16
    for i, (t, d, f, e) in enumerate(stages2):
        x = 0.028 + i * (w + gap)
        box(ax, x, y2, w, h, f"{t}\n\n{d}", fill=f, edge=e, fontsize=7.2)
        if i < len(stages2) - 1:
            arrow(ax, (x + w + 0.004, y2 + h / 2), (x + w + gap - 0.004, y2 + h / 2))

    last_x = 0.028 + 5 * (w + gap)
    arrow(ax, (last_x + w / 2, y), (last_x + w / 2, y2 + h + 0.006))
    ax.text(last_x + w / 2 - 0.012, (y + y2 + h) / 2, "v1 checkpoint\nfed into step 8",
            ha="right", va="center", fontsize=6.6, color=INK)

    note(ax, "Boxes 1-6 and 8-12 are implemented by the named scripts; box 7 is the evaluation that "
             "motivated the 64 -> 128 context change.")
    save(fig, "02_development_workflow")


